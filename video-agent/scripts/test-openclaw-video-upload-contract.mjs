import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';

const root=path.resolve(new URL('..',import.meta.url).pathname);
const plugin=await fs.readFile(path.join(root,'openclaw-plugin/index.mjs'),'utf8');
const server=await fs.readFile(path.join(root,'server.mjs'),'utf8');
const patch=await fs.readFile(path.join(root,'scripts/patch-openclaw-2026.6.11.mjs'),'utf8');
const uiPath=process.env.OPENCLAW_UI_BUNDLE||'/Users/a1234/.local/share/hyperframe-openclaw/2026.6.11/node_modules/openclaw/dist/control-ui/assets/index-BKg4kibc.js';
const ui=await fs.readFile(uiPath,'utf8');
const openClawRoot=process.env.OPENCLAW_INSTALL_ROOT||'/Users/a1234/.local/share/hyperframe-openclaw/2026.6.11/node_modules/.pnpm/openclaw@2026.6.11/node_modules/openclaw';
const distPath=path.join(openClawRoot,'dist');
const chatCandidates=(await fs.readdir(distPath)).filter(name=>name.startsWith('chat-')&&name.endsWith('.js'));
const chatSources=await Promise.all(chatCandidates.map(async name=>({name,source:await fs.readFile(path.join(distPath,name),'utf8')})));
const managedChatBundles=chatSources.filter(({source})=>source.includes('async function prestageMediaPathOffloads'));
assert.equal(managedChatBundles.length,1,'expected one installed OpenClaw chat bundle with media offload staging');
const chat=managedChatBundles[0].source;
const max=64*1024*1024;

assert.match(plugin,/DEFAULT_VIDEO_UPLOAD_BYTES\s*=\s*64\s*\*\s*1024\s*\*\s*1024/);
assert.match(plugin,/OPENCLAW_VIDEO_UPLOAD_MAX_BYTES/);
assert.match(plugin,/MAX_VIDEO_UPLOAD_MIB/);
assert.match(server,/DEFAULT_OPENCLAW_VIDEO_UPLOAD_BYTES\s*=\s*64\s*\*\s*1024\s*\*\s*1024/);
assert.match(server,/OPENCLAW_VIDEO_UPLOAD_MAX_BYTES/);
assert.match(server,/stat\.size>OPENCLAW_MAX_VIDEO_BYTES/);
assert.match(server,/mp4\|mov\|webm/);
assert.match(server,/视频附件不能使用远程 URL/);
assert.match(server,/视频附件路径无效/);
assert.match(patch,/DEFAULT_VIDEO_BYTES\s*=\s*64\s*\*\s*1024\s*\*\s*1024/);
assert.match(patch,/patchManagedMediaReceipts/);
assert.match(plugin,/auth:\s*"plugin"/);
assert.match(plugin,/loopbackRemote/);
assert.match(plugin,/origin !== `http:\/\/\$\{host\}`/);
assert.match(patch,/credentials:"same-origin"/);
assert.match(patch,/onAttachmentsError:t=>T_\(e,t\)/);
assert.match(ui,new RegExp(`r>${max}`));
assert.match(ui,new RegExp(`r<=${max}`));
assert.match(ui,/video\/mp4/);
assert.match(ui,/video\/quicktime/);
assert.match(ui,/video\/webm/);
assert.match(ui,/credentials:"same-origin"/);
assert.doesNotMatch(ui,/VIDEO_AUTH_|VIDEO_TOKEN_HASH/);
assert.match(chat,/const isManagedInboundRef = \(ref\)/);
assert.match(chat,/paths: refs\.map\(\(ref\) => isManagedInboundRef\(ref\) \? ref\.mediaRef : ref\.path\)/);
assert.match(chat,/path: isManagedInboundRef\(ref\) \? ref\.mediaRef : ref\.path/);
console.log('OpenClaw video upload contract passed: MP4/MOV/WebM, configurable 64 MiB original-media ingress, managed path, visible errors');
