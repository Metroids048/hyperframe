import assert from 'node:assert/strict';
import {requestsAutonomousExternalMedia,selectProductionAssets,isUploadedSourceExport,selectUploadedWorkflowSource} from '../lib/creative/service.mjs';

assert.equal(requestsAutonomousExternalMedia('仅使用用户上传的真实视频画面，不引入本地库、网络素材或生成画面'),false);
assert.equal(requestsAutonomousExternalMedia('禁止外部下载/研究媒体、生成商品图或镜头；缺素材时说明缺口'),false);
assert.equal(requestsAutonomousExternalMedia('不要调用外部素材下载，使用附件剪辑'),false);
assert.equal(requestsAutonomousExternalMedia('自行检索外部素材补充使用环境'),true);
assert.equal(requestsAutonomousExternalMedia('寻找网络视频补齐场景补镜'),true);
console.log('external media intent: 5 checks passed');
const assets=[{id:'original',sha256:'same-upload'},{id:'duplicate-upload',sha256:'same-upload'},{id:'unrelated-web-image',sha256:'external'}];
assert.deepEqual(selectProductionAssets(assets,{message:'仅使用用户上传的真实画面',attachmentIds:['duplicate-upload']}),[assets[0]]);
assert.deepEqual(selectProductionAssets(assets,{message:'唯一允许使用的真实素材是本会话上传文件',attachmentIds:['original']}),[assets[0]]);
assert.deepEqual(selectProductionAssets(assets,{message:'使用工程全部素材'}),[assets[0],assets[2]]);
console.log('production asset scope: 3 checks passed');
const source={mediaMetadata:{width:1080,height:1920,duration:30,hasAudio:false}};
const request={message:'仅使用上传原片，原样导出。保持画面不变。不添加字幕、音乐或旁白。',output:{width:1080,height:1920,durationSeconds:30,fps:30},audio:{mode:'silent'}};
assert.equal(isUploadedSourceExport(request,source),true);
assert.equal(isUploadedSourceExport({...request,output:{...request.output,durationSeconds:15}},source),false);
assert.equal(isUploadedSourceExport({...request,output:{...request.output,width:1920}},source),false);
assert.equal(isUploadedSourceExport({...request,message:'原样导出，然后添加字幕'},source),false);
assert.equal(isUploadedSourceExport({...request,message:'仅使用上传原片，原样导出。不新增文字或音频。'},source),true);
assert.equal(isUploadedSourceExport({...request,message:'制作Steam Deck种草片，呈现两个主机细节'},source),false);
assert.equal(isUploadedSourceExport(request,{mediaMetadata:{...source.mediaMetadata,hasAudio:true}}),false);
console.log('unchanged source export intent: 7 checks passed');
const uploaded={...source,id:'upload',kind:'video'};
const existing={currentRevisionId:'existing-revision',assets:[uploaded]};
assert.equal(selectUploadedWorkflowSource(existing,{...request,attachmentIds:['upload']}),uploaded);
assert.equal(selectUploadedWorkflowSource(existing,{...request,message:'在原片开头添加标题',attachmentIds:['upload']}),null);
assert.equal(selectUploadedWorkflowSource({...existing,currentRevisionId:null},{message:'在原片开头添加标题',attachmentIds:['upload']}),uploaded);
console.log('source workflow revision scope: 3 checks passed');
