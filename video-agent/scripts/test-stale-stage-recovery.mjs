import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {AgentKernel,AgentRunStore} from '../lib/edit/agent-kernel.mjs';
import {ToolRegistry} from '../lib/edit/tool-registry.mjs';
import {invalidateStageResults} from '../lib/creative/recovery.mjs';
const dir=await fs.mkdtemp(path.join(os.tmpdir(),'stage-recovery-'));
const store=new AgentRunStore(dir),registry=new ToolRegistry();let calls=0;
registry.register('narration.prepare',async()=>({script:++calls===1?'old':'retained-new'}));
const kernel=new AgentKernel({store,registry,planner:async({run})=>run.checkpoints.narration?{kind:'complete'}:{kind:'tool',tool:'narration.prepare',checkpoint:'narration',input:{}}});
const first=await kernel.start({userRequest:'retained narration'});
first.checkpoints.narration={idempotencyKey:'latest-revised',result:{script:'retained-new'}};
first.toolResults.push({tool:'narration.prepare',idempotencyKey:'latest-revised',status:'completed',result:{script:'retained-new'}});
first.artifacts.narrationHistory=[{script:'old'}];first.modelCalls=98;
first.toolResults.push({tool:'assets.observe',idempotencyKey:'unaffected',status:'completed',result:{ok:true}});
invalidateStageResults(first,['narration'],{code:'IMPLEMENTATION_CHANGED'});
assert.equal(first.toolResults.filter(r=>r.tool==='narration.prepare'&&r.status==='completed').length,0);
assert.equal(first.toolResults.at(-1).status,'completed');assert.equal(first.modelCalls,98);
assert.deepEqual(first.artifacts.narrationHistory,[{script:'old'}]);
assert.equal(first.status,'recoverable');assert.equal(first.resultRevisionId,null);assert.equal(first.verification,null);await store.open(first);
const resumed=await kernel.resume(first.id);
assert.equal(resumed.status,'completed');assert.equal(calls,2);
assert.equal(resumed.checkpoints.narration.result.script,'retained-new');
assert.equal(resumed.modelCalls,98);
console.log('PASS: old successful stage variants cannot resurrect after invalidation; unrelated evidence, history and model count retained');
