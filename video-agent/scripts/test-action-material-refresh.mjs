import assert from 'node:assert/strict';
import {refreshActionMaterial} from '../lib/creative/recovery.mjs';
import {queryEvidence} from '../lib/creative/evidence-index.mjs';

const material={actions:[{id:'load',importance:'necessary',dependsOn:[]}]};
const run={status:'running',modelCalls:15,steps:30,repairCount:2,artifacts:{actionInspections:[{key:'dense-1'}],materialActionEvidenceHash:'old'},checkpoints:{material:{result:material,idempotencyKey:'ma'},story:{result:{},idempotencyKey:'new-story'},narration:{result:{asset:{sha256:'paid-voice'}}},'action-inspection-1':{result:{key:'dense-1'}},'shot-0':{result:{},idempotencyKey:'shot'}},toolCalls:[{name:'story.plan',idempotencyKey:'old-story'}],toolResults:[{tool:'story.plan',idempotencyKey:'old-story',status:'completed'},{tool:'story.plan',idempotencyKey:'new-story',status:'completed'},{tool:'scene.author',idempotencyKey:'shot',status:'completed'}]};
assert.equal(refreshActionMaterial(run,'new'),true);
assert.deepEqual(run.artifacts.priorActionMaterial,material);
assert.equal(run.checkpoints.material,undefined);
assert.equal(run.checkpoints.story,undefined);
assert.equal(run.checkpoints['shot-0'],undefined);
assert.ok(run.toolResults.every(r=>r.status==='invalidated'));
assert.equal(run.checkpoints.narration.result.asset.sha256,'paid-voice');
assert.equal(run.checkpoints['action-inspection-1'].result.key,'dense-1');
assert.deepEqual([run.modelCalls,run.steps,run.repairCount],[15,30,2]);
assert.equal(refreshActionMaterial(run,'new'),false);
run.checkpoints.material={result:structuredClone(material)};
run.artifacts.materialActionEvidenceHash='new';
assert.equal(refreshActionMaterial(run,'new'),false);
assert.equal(run.artifacts.materialEvidenceHistory.length,1);
assert.equal(refreshActionMaterial(run,'newer'),true);
assert.equal(run.artifacts.materialEvidenceHistory.length,2);
console.log('Action material refresh: new evidence invalidates all dependent variants once; audio, inspections, obligations and budgets retained.');
const entries=[...Array.from({length:30},(_,i)=>({id:'old-'+i,assetId:'source',batchKey:'overview',startSeconds:i,endSeconds:i+1,times:[i]})),...Array.from({length:17},(_,i)=>({id:'action-'+i,assetId:'source',batchKey:'action',startSeconds:0,endSeconds:12,times:[i*.25]}))];
const selected=queryEvidence({entries},{requiredBatchKeys:['action'],limit:24});
assert.equal(selected.records.length,24);
assert.equal(selected.records.filter(r=>r.batchKey==='action').length,17);
assert.equal(selected.records.slice(0,17).every(r=>r.batchKey==='action'),true);
assert.throws(()=>queryEvidence({entries},{requiredBatchKeys:['action'],limit:12}),{code:'OBSERVATION_BUDGET'});
console.log('Required action sequence reaches image selection intact; old overview uses remaining slots; budget overflow fails explicitly.');
